import { pluralize } from "../../../lib/format";

/**
 * Почему «+» у позиции упёрся.
 *
 * Живёт отдельно, потому что счётчик стоит в двух местах — в каталоге и в
 * составе заявки, — а объяснение должно быть одно и то же: разные формулировки
 * на одну ситуацию читаются как разные ситуации.
 *
 * `availableQuantity` уже посчитан на выбранные даты и с исключением самой
 * правимой брони, поэтому ноль означает ровно «всё разобрали другие брони»,
 * а не «в парке ничего нет».
 */
export function maxReasonFor(availableQuantity: number, quantity: number): string | null {
  if (quantity < availableQuantity) return null;
  if (availableQuantity <= 0) {
    return "На выбранные даты свободных нет — всё занято другими бронями. Поменяйте даты или уберите позицию.";
  }
  return `Больше нет: на выбранные даты свободно ${availableQuantity} ${pluralize(availableQuantity, "штука", "штуки", "штук")}, и все уже в смете.`;
}
